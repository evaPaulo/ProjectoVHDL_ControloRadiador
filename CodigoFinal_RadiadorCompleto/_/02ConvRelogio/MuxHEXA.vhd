LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY MuxHEXA IS
	PORT (
		i0, i1, i2 : IN STD_LOGIC_VECTOR(1 DOWNTO 0);
		sel : IN STD_LOGIC_VECTOR(1 DOWNTO 0);
		yout : OUT STD_LOGIC_VECTOR(1 DOWNTO 0));
END MuxHEXA;

ARCHITECTURE compMuxHEXA OF MuxHEXA IS
BEGIN

	yout <= i2 WHEN (sel = "11") ELSE
		i1 WHEN (sel = "10") ELSE
		i0;

END compMuxHEXA;